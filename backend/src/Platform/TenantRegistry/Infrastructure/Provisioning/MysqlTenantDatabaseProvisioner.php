<?php

declare(strict_types=1);

namespace App\Platform\TenantRegistry\Infrastructure\Provisioning;

use App\Platform\TenantRegistry\Domain\InvalidTenantInputException;
use App\Platform\TenantRegistry\Domain\TenantDatabaseProvisioner;
use App\Platform\TenantRegistry\Domain\TenantDatabaseSpec;
use App\Platform\TenantRegistry\Domain\TenantInputValidator;
use App\Platform\TenantRegistry\Domain\TenantProvisioningException;
use Symfony\Component\DependencyInjection\Attribute\Autowire;

final class MysqlTenantDatabaseProvisioner implements TenantDatabaseProvisioner
{
    public function __construct(
        private readonly TenantInputValidator $validator,
        #[Autowire('%app.tenant_database_admin_url%')]
        private readonly string $adminUrl,
        #[Autowire('%app.tenant_database_user_host%')]
        private readonly string $userHost,
    ) {
    }

    public function provision(TenantDatabaseSpec $spec): void
    {
        $this->assertSpec($spec);
        $pdo = $this->admin();
        $password = $pdo->quote($spec->password);
        if (!is_string($password)) {
            throw new TenantProvisioningException('The tenant database could not be created.');
        }
        $account = sprintf("'%s'@'%s'", $spec->username, $this->userHost);
        try {
            $pdo->exec(sprintf(
                'CREATE DATABASE IF NOT EXISTS `%s` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci',
                $spec->databaseName,
            ));
            $pdo->exec(sprintf('CREATE USER IF NOT EXISTS %s IDENTIFIED BY %s', $account, $password));
            $pdo->exec(sprintf('ALTER USER %s IDENTIFIED BY %s', $account, $password));
            $pdo->exec(sprintf('GRANT ALL PRIVILEGES ON `%s`.* TO %s', $spec->databaseName, $account));
        } catch (\PDOException) {
            throw new TenantProvisioningException('The tenant database could not be created.');
        }
    }

    public function drop(string $databaseName, string $username): void
    {
        $databaseName = $this->validator->databaseName($databaseName);
        $username = $this->validator->databaseUser($username);
        $pdo = $this->admin();
        $account = sprintf("'%s'@'%s'", $username, $this->userHost);
        try {
            $pdo->exec(sprintf('DROP DATABASE IF EXISTS `%s`', $databaseName));
            $pdo->exec(sprintf('DROP USER IF EXISTS %s', $account));
        } catch (\PDOException) {
            throw new TenantProvisioningException('The tenant database could not be removed.');
        }
    }

    private function assertSpec(TenantDatabaseSpec $spec): void
    {
        $this->validator->databaseName($spec->databaseName);
        $this->validator->databaseUser($spec->username);
        if (!preg_match('/^[a-f0-9]{48}$/', $spec->password)) {
            throw new InvalidTenantInputException('Database password was not generated by the platform.');
        }
        if (!preg_match('/^(%|[A-Za-z0-9._-]{1,64})$/', $this->userHost)) {
            throw new \LogicException('TENANT_DATABASE_USER_HOST is invalid.');
        }
    }

    private function admin(): \PDO
    {
        $parts = parse_url($this->adminUrl);
        if (!is_array($parts) || ($parts['scheme'] ?? '') !== 'mysql' || !isset($parts['host'], $parts['user'], $parts['pass'])) {
            throw new \LogicException('TENANT_DATABASE_ADMIN_URL must be a mysql URL with a user and password.');
        }
        $port = isset($parts['port']) ? (int) $parts['port'] : 3306;
        $dsn = sprintf('mysql:host=%s;port=%d;charset=utf8mb4', $parts['host'], $port);
        try {
            return new \PDO($dsn, rawurldecode((string) $parts['user']), rawurldecode((string) $parts['pass']), [
                \PDO::ATTR_ERRMODE => \PDO::ERRMODE_EXCEPTION,
            ]);
        } catch (\PDOException) {
            throw new TenantProvisioningException('The tenant database server could not be reached.');
        }
    }
}
